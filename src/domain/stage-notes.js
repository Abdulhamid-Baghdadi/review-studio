const withoutMd = name => chars(name).slice(0, -3).join("");

/** 00 - Review timeline.md: stages, protocol, amendments, idea log and every event (newest first). */
export function timelineNote({ reviewName, reviewLink, st, today }) {
  const type = reviewType(st);
  const lines = [frontmatter.serialize({ type: "review-timeline", review: reviewLink, generated: today }),
    `# ${reviewName} — timeline\n`,
    `> [!info] Generated by Scoping Review Workbench. Links: [[03 - Search strategy]] · [[05 - Protocol]] · [[08 - Screening.base]] · [[14 - PRISMA flow]] · [[${withoutMd(type.checklistFile)}]]\n`,
    `Review type: ${type.label}, reported to ${type.guideline}.\n`,
    "## Stages\n", "| Stage | Optional | Status | Updated | Skip reason |", "|---|:-:|---|---|---|"];
  for (const { key, title, optional } of type.stages) {
    const s = st.stages[key];
    lines.push(`| ${title} | ${optional ? "yes" : ""} | ${STATUS_ICON[s.status]} ${s.status} | ${s.updated} | ${s.reason} |`);
  }
  const p = st.protocol;
  lines.push("", "## Protocol\n", `- Locked: ${p.locked || "no"}` + (p.file ? ` — [[${withoutMd(p.file)}]]` : ""),
    `- Registration: ${p.registration || "—"}`, `- Git commit: ${p.commit || "—"}`, "",
    "## Amendments after locking\n", "| When | What | Reason |", "|---|---|---|",
    ...(st.amendments.length ? st.amendments.map(a => `| ${a.when} | ${a.what} | ${a.reason} |`) : ["| — | | |"]));
  if (st.idea.length) lines.push("", "## Idea log\n", ...st.idea.map(i => `- **${i.when}** — ${i.text}`));
  lines.push("", "## Events\n", "| When | Stage | What |", "|---|---|---|",
    ...[...st.events].reverse().map(e => `| ${e.when} | ${stageOf(st, e.stage)?.title ?? e.stage} | ${String(e.text).replaceAll("|", "/")} |`));
  return lines.join("\n") + "\n";
}

/**
 * 03 - Search strategy.md: questions, concept table, search strings and pilot runs; null while there is
 * nothing to show (no concepts yet and no earlier note).
 */
export function strategyNote({ reviewName, reviewLink, st, today, exists }) {
  if (!st.concepts.length && !exists) return null;
  const q = st.questions, Q = reviewType(st).question;
  const lines = [frontmatter.serialize({ type: "search-strategy", review: reviewLink, generated: today }),
    `# ${reviewName} — search strategy\n`, "> [!info] Generated by the review tool.\n",
    "## Review questions\n", `- **${Q.population}:** ${q.population || "—"}`, `- **${Q.concept}:** ${q.concept || "—"}`,
    `- **${Q.context}:** ${q.context || "—"}`, ...(Q.outcome ? [`- **${Q.outcome}:** ${q.outcome || "—"}`] : []), "", `**Main question.** ${q.main || "—"}\n`, ...q.sub.map(s => `- ${s}`)];
  if (q.history.length) {
    lines.push("", "<details><summary>Earlier versions</summary>\n",
      ...[...q.history].reverse().map(h => `- **${h.when}** (${h.why || "no reason given"}): ${h.main || "—"}`), "\n</details>");
  }
  lines.push("", "## Concept table\n", "| Concept | Role | Terms |", "|---|---|---|",
    ...st.concepts.map(c => `| ${c.name} | ${c.role ?? "AND"} | ${(c.terms ?? []).join("; ")} |`), "", "## Search strings\n");
  for (const db of st.queries.databases) {
    lines.push(`**${db}**${st.queries.manual[db] ? " (edited by hand)" : ""}`, "", "```", buildQuery(st, db) || "(no concepts yet)", "```", "");
  }
  lines.push("## Pilot runs\n", "| When | Database | Hits | Test set retrieved | Note |", "|---|---|---:|---:|---|",
    ...(st.pilots.length ? st.pilots.map(p => `| ${p.when} | ${p.database} | ${p.hits} | ${p.retrieved}/${p.test_set} | ${p.note} |`) : ["| — | | | | |"]));
  const last = [...st.pilots].reverse().find(p => p.missed?.length);
  if (last) lines.push("", `<details><summary>Test-set papers missed by the last pilot (${last.when})</summary>\n`, ...last.missed.map(m => `- ${m}`), "\n</details>");
  return lines.join("\n") + "\n";
}

/**
 * Evidence the tool can see for each item of the review's checklist ("" = only the reviewer can judge).
 * @param {object} p @param {object} p.st @param {import("./flow.js").SearchRow[]} p.searches
 * @param {import("./frontmatter.js").Properties[]} p.records @param {boolean} p.guideExists @param {boolean} p.flowExists
 * @returns {Record<string, string>} checklist item → evidence
 */
export function checklistEvidence({ st, searches, records, guideExists, flowExists }) {
  const s = st.stages, type = reviewType(st), words = type.words;
  const databases = searches.filter(r => r.kind === "database").length;
  const facts = {
    questions: st.questions.main ? "questions written" : "",
    registration: isLocked(st) ? `registered ${st.protocol.locked}` : s.registration.status === "skipped" ? "registration skipped: " + s.registration.reason : "",
    criteria: guideExists ? "exclusion reasons defined" : "",
    sources: searches.length ? `${databases} database search${databases === 1 ? "" : "es"} logged` : "",
    strings: databases ? "full strings in Search strategy" : "",
    screening: records.some(r => r.ta_decision !== "pending") ? "screening decisions recorded" : "",
    dataItems: `${st.charting.fields.length} data items defined`,
    appraisalMethods: s.appraisal.status === "skipped" ? "skipped: " + s.appraisal.reason : s.appraisal.status !== "not-started" ? `${words.appraisal} recorded` : "",
    flow: flowExists && searches.length ? "PRISMA flow generated" : "",
    charting: s.charting.status !== "not-started" ? `${words.charting} table` : "",
    appraisalData: s.appraisal.status === "skipped" ? "not performed (skipped)" : "",
  };
  return Object.fromEntries(Object.entries(type.evidence).map(([fact, n]) => [n, facts[fact] ?? ""]));
}

/** The review's checklist note: 14 - PRISMA-ScR checklist.md */
export function checklistNote({ reviewName, reviewLink, st, today, evidence }) {
  const type = reviewType(st), ticks = checklistOf(st);
  const lines = [frontmatter.serialize({ type: "prisma-checklist", review: reviewLink, guideline: type.guideline, generated: today }),
    `# ${reviewName} — ${type.guideline} checklist\n`,
    `> [!info] Generated by the review tool. Tick items and give their location in the manuscript in the tool. Check the official checklist (${type.guidelineCitation}) before submitting.\n`,
    "| # | Item | Reported? | Location | Evidence in the vault |", "|---:|---|:-:|---|---|"];
  for (const { n, item, desc } of type.checklist) {
    const c = ticks[n] ?? {};
    lines.push(`| ${n} | **${item}** — ${desc} | ${c.done ? "✔" : ""} | ${c.location ?? ""} | ${evidence[n] ?? ""} |`);
  }
  return lines.join("\n") + "\n";
}

/** 12 - Charting.base: the charting form as a table over the included records (and appraisal, if used). */
export function chartingBase(st, withAppraisal) {
  const views = [["Charting", ["file.name", "year", ...st.charting.fields.map(f => fullName(`chart_${f.name}`))]]];
  if (withAppraisal) views.push(["Appraisal", ["file.name", "year", fullName("chart_study_type"), "appraisal", "appraisal_note"]]);
  return "views:\n" + views.map(([name, order]) =>
    `  - type: table\n    name: ${name}\n    filters:\n      and:\n${RECORD_FILTERS.map(f => `        - ${f}\n`).join("")}        - ${fullName("ft_decision")} == "include"\n    order:\n`
    + order.map(c => `      - ${c}\n`).join("")
    + "    sort:\n      - property: file.name\n        direction: ASC\n    columnSize:\n      file.name: 380\n").join("");
}

/** Charting and appraisal of the included records as CSV (with a BOM, for Excel). */
export function chartingCsv(st, includedProps) {
  const keys = [...st.charting.fields.map(f => `chart_${f.name}`), "appraisal", "appraisal_note"];
  const rows = includedProps.map(f => [f.record_id, f.authors, f.year, f.title, f.journal, f.doi, ...keys.map(k => f[k] ?? "")]);
  return "﻿" + writeRows([["record_id", "authors", "year", "title", "journal", "doi", ...keys.map(fullName)], ...rows]);
}

const authorList = f => String(f.authors ?? "").split(";").map(a => a.trim()).filter(Boolean);

/** A record's citation key: its `citekey` (e.g. from Better BibTeX in Zotero), else Surname + year + record id. */
export function citekeyOf(f) {
  if (f.citekey) return String(f.citekey);
  const first = (authorList(f)[0] ?? "anon").split(",")[0].trim().split(/\s+/).at(-1) ?? "";
  return `${first}${f.year}${f.record_id}`.replace(/[^\p{L}\p{N}_]/gu, "");
}

/**
 * The included records as BibTeX (@article entries keyed by {@link citekeyOf}).
 * @param {object[]} includedProps record properties, optionally with `abstract` and `keywords`
 */
export function bibtex(includedProps) {
  return includedProps.map(f => {
    const fields = { title: f.title, author: authorList(f).join(" and "), year: f.year, journal: f.journal, doi: f.doi,
      abstract: f.abstract, keywords: String(f.keywords ?? "").split(";").map(k => k.trim()).filter(Boolean).join(", ") };
    return `@article{${citekeyOf(f)},\n` + Object.entries(fields).filter(([, v]) => v).map(([k, v]) => `  ${k} = {${v}}`).join(",\n") + "\n}\n";
  }).join("\n");
}

/**
 * The included records as RIS for Zotero: tagged with the review and record id, and with the full text
 * linked relative to 07 - Exports so Zotero attaches it when this file is imported from the review folder.
 * @param {object[]} includedProps record properties, optionally with `abstract` and `keywords`
 * @param {string} reviewName
 */
export function zoteroRis(includedProps, reviewName) {
  return includedProps.map(f => {
    const lines = [["TY", "JOUR"], ["ID", citekeyOf(f)], ["TI", f.title], ...authorList(f).map(a => ["AU", a]),
      ["PY", f.year], ["T2", f.journal], ["DO", f.doi], ["UR", f.url], ["AB", String(f.abstract ?? "").replace(/\s*\n\s*/g, " ")],
      ...String(f.keywords ?? "").split(";").map(k => ["KW", k.trim()]),
      ["KW", `review:${reviewName}`], ["KW", "included"], ["KW", `record:${f.record_id}`]];
    const pdf = /^\[\[(.+\.pdf)\]\]$/i.exec(String(f.pdf ?? ""))?.[1];
    if (pdf && f.pdf_status === "found") lines.push(["L1", `../${FULLTEXT_DIR}/${pdf}`]);
    lines.push(["N1", `Citation Key: ${citekeyOf(f)}`]);
    return lines.filter(([, v]) => v !== undefined && v !== "").map(([t, v]) => `${t}  - ${v}`).join("\r\n") + "\r\nER  - \r\n";
  }).join("\r\n");
}
